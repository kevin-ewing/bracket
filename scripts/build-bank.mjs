import fs from 'node:fs/promises';
import {makeCalendar} from './year-calendar.mjs';
import {VERSION,EPOCH} from '../src/core.js';
import {buildWorldLibrary} from './world-library.mjs';
import {worldReview} from './world-review.mjs';
import { editQuestion } from './editorial.mjs';
import { reviewQuestion } from './review-questions.mjs';
import { qualityReview } from './quality-review.mjs';
import { buildFermiLibrary } from './fermi-library.mjs';
import { explainQuestion } from './explanations.mjs';
import { getModelQuestions } from '../src/models.js';
const bank=JSON.parse(await fs.readFile(new URL('../data/questions.json',import.meta.url),'utf8'));
const categories=['The human scale','Objects & scale','The everyday world','Space & time','Exponential thinking'];
for(let i=0;i<8;i++){
 const date=new Date(Date.UTC(2026,10,10+i)).toISOString().slice(0,10);
 for(const q of getModelQuestions(date)){
  q.id='model-'+q.id;
  if(bank.some(old=>old.id===q.id))continue;
  q.entity=q.id;q.category=({'The human scale':'Sports & everyday','Objects & scale':'Consulting & logic','The everyday world':'Sports & everyday','Space & time':'Space','Exponential thinking':'Consulting & logic'})[q.category];
  q.source={name:'Bracket · original mathematical model',url:'https://www.nist.gov/pml/owm/metric-si-prefixes',note:'Original reasoning problem. All model assumptions are in the prompt. NIST provides unit-conversion conventions.',retrieved:'2026-11-10'};
  bank.push(q);
 }
}
bank.sort((a,b)=>a.id.localeCompare(b.id,'en'));
const reviews=bank.map(editQuestion).map(reviewQuestion);
const sourceReviewed=reviews.map(r=>qualityReview(r.question));
const derivedReviewed=reviews.filter(r=>r.derived).map(r=>qualityReview(r.derived));
const authored=[...buildFermiLibrary(),...buildWorldLibrary()];
const historicalReview=[...sourceReviewed,...derivedReviewed,...authored].map(worldReview);
const featured=historicalReview.filter(q=>q.review.status==='approved').map(q=>q.id.startsWith('world-')?q:explainQuestion(q));
const calendar=makeCalendar(featured);
const edited=calendar.selected.map(item=>item.q);
const reviewed=[...historicalReview,...calendar.selected.filter(item=>item.row).map(item=>item.q)];
if(sourceReviewed.length!==bank.length)throw Error('Incomplete bank review');

// Store a recipe once and keep each source observation as a compact record.
// Resolve the same records to full questions in Node and in the browser.
const recipeIndex=new Map(), recipes=[];
const slots=calendar.selected.map(item=>{
 if(!item.row)return item.q;
 const key=item.row.series+':'+item.spec.category;
 if(!recipeIndex.has(key)){
  recipeIndex.set(key,recipes.length);
  recipes.push(item.spec);
 }
 return [recipeIndex.get(key),item.row];
});
const bankModule=`// Frozen calendar. Generated by scripts/build-bank.mjs.
import {yearQuestion} from './year-questions.js';
const recipes=${JSON.stringify(recipes)};
const countries=${JSON.stringify(calendar.countries)};
const slots=${JSON.stringify(slots)};
export const coverageDays=${calendar.coverageDays};
export default slots.map(slot=>Array.isArray(slot)?yearQuestion(slot[1],recipes[slot[0]],countries):slot);
`;
await fs.writeFile(new URL('../src/bank.js',import.meta.url),bankModule);
await fs.writeFile(new URL('../data/question-bank.json',import.meta.url),JSON.stringify(edited,null,2)+'\n');
await fs.writeFile(new URL('../data/question-review.json',import.meta.url),JSON.stringify({sourceReviewed:sourceReviewed.length,externalScreened:867,newCandidates:calendar.candidates.length,reviewed:reviewed.length,approved:edited.length,coverageDays:calendar.coverageDays,starts:EPOCH,through:calendar.through,excluded:reviewed.filter(q=>q.review.status==='excluded').length,entries:reviewed.map(q=>({id:q.id,question:q.question,unit:q.unitLabel,context:q.context,...q.review}))},null,2)+'\n');
const csvCell=value=>'"'+String(value??'').replaceAll('"','""')+'"';
const columns=['id','category','question','context','answer','unit','hint','estimation_route','calculation','reference_assumptions','source','source_url'];
const rows=edited.map(q=>[q.id,q.category,q.question,q.context,q.answer,q.unitLabel,q.hint,q.explanation.approach,q.steps.join("\n"),q.explanation.assumptions,q.source.name,q.source.url]);
await fs.writeFile(new URL('../data/question-bank.csv',import.meta.url),'\ufeff'+[columns,...rows].map(row=>row.map(csvCell).join(',')).join('\r\n')+'\r\n');
const counts=edited.reduce((o,q)=>(o[q.category]=(o[q.category]||0)+1,o),{});
await fs.writeFile(new URL('../data/release.json',import.meta.url),JSON.stringify({version:VERSION,coverageDays:calendar.coverageDays,starts:EPOCH,through:calendar.through,count:edited.length,reviewed:reviewed.length,excluded:reviewed.filter(q=>q.review.status==='excluded').length,categories:counts},null,2)+'\n');
const explanationText='# Reviewed question explanations\n\n'+edited.map(q=>`## ${q.question}\n\n${q.id} · ${q.unitLabel} · Reference answer: ${q.answer}\n\n**How to estimate it:** ${q.explanation.approach}\n\n${q.steps.map((step,i)=>`${i+1}. ${step}`).join('\n')}\n\n**Reference assumptions:** ${q.explanation.assumptions}\n\n${q.sources.map(source=>`- [${source.name}](${source.url}): ${source.supports}`).join('\n')}\n`).join('\n');
await fs.writeFile(new URL('../data/EXPLANATIONS.md',import.meta.url),explanationText);
console.log('Reviewed',reviewed.length,'source questions;',edited.length,'reasoning questions approved.');
